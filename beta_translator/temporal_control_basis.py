"""Cubic angle controls; all contacts and constraints are evaluated at native frames.

This is a trajectory parameterization, never Cartesian pose/video interpolation.
Every exported frame is generated by the same fixed-length forward kinematics.
"""
import numpy as np
from scipy.interpolate import BSpline
from scipy.sparse import coo_matrix,eye,diags
from scipy.sparse.linalg import spsolve


def control_map(problem,stride=8):
    n=problem.n;degree=min(3,n-1)
    qdim=getattr(problem,'qdim',28);statedim=qdim+12
    if type(stride) is not int or stride<1:raise ValueError('Positive integer control stride required')
    knots=np.r_[np.zeros(degree+1),np.arange(stride,n-1,stride),np.full(degree+1,n-1.)]
    B=BSpline.design_matrix(np.arange(n,dtype=float),knots,degree).tocsr();k=B.shape[1]
    b=B.tocoo();rows=[];cols=[];values=[]
    for d in range(qdim):
        rows.append(b.row*statedim+d);cols.append(b.col*qdim+d);values.append(b.data)
    # Omit fixed zero force variables entirely; retain all observed force unknowns.
    ids=(np.arange(n)[:,None]*statedim+np.arange(qdim,statedim)).ravel()
    force_ids=ids[problem.upper[ids]>problem.lower[ids]]
    rest=np.r_[force_ids,np.arange(n*statedim,len(problem.initial))]
    rows.append(rest);cols.append(k*qdim+np.arange(len(rest)));values.append(np.ones(len(rest)))
    T=coo_matrix((np.concatenate(values),(np.concatenate(rows),np.concatenate(cols))),
        shape=(len(problem.initial),k*qdim+len(rest))).tocsr()
    q=problem.initial[:n*statedim].reshape(n,statedim)[:,:qdim]
    controls=spsolve((B.T@B+1e-10*eye(k)).tocsc(),B.T@q)
    low=np.r_[np.tile(problem.lower[:qdim],k),problem.lower[rest]]
    high=np.r_[np.tile(problem.upper[:qdim],k),problem.upper[rest]]
    initial=np.clip(np.r_[controls.ravel(),problem.initial[rest]],low,high)
    return T,initial,low,high,dict(kind='clamped_cubic_joint_coordinate_controls',
        control_stride_frames=int(stride),control_points=int(k),native_frames=n,variables=T.shape[1],
        guarantees='Nonnegative partition of unity preserves coordinate ROM; rate/acceleration constraints are tested on every native frame; no post-fit filtering.')


from .trial2_anatomy_optimizer import AnatomicalProblem
from .restored_sequence_solver import solve as restored_solve


class ControlledProblem(AnatomicalProblem):
    """One complete sequence, globally shared controls, native-frame residuals."""
    def solve(self,iterations=160,progress=None):
        T,initial,lower,upper,info=control_map(self,8)
        def evaluate(z):
            residual,J=self.evaluate(T@z)
            return residual,J@T
        solver=restored_solve(evaluate,initial,lower,upper,self.hard_rates@T,iterations,progress)
        controls=solver.pop('x');x=T@controls
        solver['parameterization']=info
        y=(self.expand@x).reshape(self.n,48);g=self.geometry(y)
        return dict(**g,parameters=x,values=y[:,:40],anatomical_q=y[:,:28],
            control_values=controls[:info['control_points']*28].reshape(-1,28),
            control_stride=np.array(8),episode_uv=x[-2*self.e:].reshape(self.e,2),offsets=self.base.offset,solver=solver)
